def build_dataset() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    all_rows = []

    for raw in RAW_SAMPLES:
        features = extract_features(raw)
        row = {
            "sample_id": raw["sample_id"],
            "scenario_id": raw["scenario_id"],
            "url": raw["url"],
            "hostname": raw["hostname"],
            "claimed_service": raw["claimed_service"],
            "known_brand": raw["known_brand"],
            "official_domain": raw["official_domain"],
            "source": raw["source"],
            "license": raw["license"],
            "collection_date": raw["collection_date"],
            "environment_type": raw["environment_type"],
            "ground_truth": raw["ground_truth"],
            "threat_types": raw["threat_types"],
            "expected_behavior": raw["expected_behavior"],
            "expected_data_target": raw["expected_data_target"],
            "annotation_method": raw["annotation_method"],
            "annotation_confidence": raw["annotation_confidence"],
            "label": raw["ground_truth"],
            **features,
        }
        all_rows.append(row)

    if not all_rows:
        raise ValueError("No rows generated for Dataset v0.2")

    fieldnames = list(all_rows[0].keys())
    with open(DATASET_V0_2_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(all_rows)

    metadata = {
        "dataset_name": "CAPSTONE-1 Dataset v0.2",
        "version": "0.2.0",
        "total_samples": len(all_rows),
        "legitimate_samples": sum(1 for r in all_rows if r["ground_truth"] == "legitimate"),
        "phishing_samples": sum(1 for r in all_rows if r["ground_truth"] == "phishing"),
        "feature_count": len(fieldnames),
        "generation_date": "2026-08-22",
        "provenance": {
            "sources": ["curated_ground_truth", "synthetic_controlled_adversarial", "counterfactual_controlled_experiment"],
            "license": "CC-BY-4.0",
        },
    }

    with open(DATASET_V0_2_META, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    print(f"Dataset v0.2 built: {len(all_rows)} samples saved to {DATASET_V0_2_CSV}")
    print(f"Metadata saved to {DATASET_V0_2_META}")


if __name__ == "__main__":
    build_dataset()
